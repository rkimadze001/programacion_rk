package ejercicio11;

/**
 * Programa: muestre por pantalla el mensaje "Hola" seis veces acompañado por un
 * numero que se incrementa cada vez.
 * @author RusudanKimadze
 */
public class Ejercicio11 {

    /**
     * @param args the command line arguments
     */
    public static void main(String[] args) {
        //bucle para imprimir
        for(int i=1; i<7; i++){
            System.out.print("- Hola" + i + " ");
        }
        // imprimiros una barra en final
        System.out.println("- ");  
    }
    
}
