package ejercicion30;

/**
 *Programa: Utilizando la conversión Explicita (cast) es fácil averiguar 
 * el código ASCII de un carácter cualquiera (Por ejemplo (int) ‘A’;). 
 * Realiza un programa que muestre el código ASCII de los siguientes 
 * caracteres: A B C a b c 0 1 2 $ * + / y el carácter en blanco.
 * @author RusudanKimadze
 */
public class Ejercicion30 {

    /**
     * @param args the command line arguments
     */
    public static void main(String[] args) {
        
        //imprimir ASCII codigo de A
        System.out.println("El código ASCII de A es: " + (int)'A');
        
        //imprimir ASCII codigo de B
        System.out.println("El código ASCII de B es: " + (int)'B');
        
        //imprimir ASCII codigo de C
        System.out.println("El código ASCII de C es: "+ (int)'C');
       
        //imprimir ASCII codigo de a
        System.out.println("El código ASCII de a es: "+ (int)'a');
       
        //imprimir ASCII codigo de b
        System.out.println("El código ASCII de b es: "+ (int)'b');
        
        //imprimir ASCII codigo de c
        System.out.println("El código ASCII de c es: "+ (int)'c');
        
        //imprimir ASCII codigo de 0
        System.out.println("El código ASCII de 0 es: "+ (int)'0');
        
        //imprimir ASCII codigo de 1
        System.out.println("El código ASCII de 1 es: "+ (int)'1');
        
        //imprimir ASCII codigo de 2
        System.out.println("El código ASCII de 2 es: "+ (int)'2');
        
        //imprimir ASCII codigo de $ 
        System.out.println("El código ASCII de $ es: "+ (int)'$');
        
        //imprimir ASCII codigo de * 
        System.out.println("El código ASCII de * es: "+ (int)'*');
        
        //imprimir ASCII codigo de + 
        System.out.println("El código ASCII de + es: "+ (int)'+');
        
        //imprimir ASCII codigo de / 
        System.out.println("El código ASCII de / es: "+ (int)'/');
        
        //imprimir ASCII codigo de el carácter en blanco 
        System.out.println("El código ASCII de el carácter en blanco es: "+ (int)' ');

    }
    
}
